    /**
     * Handles the registration process when the user presses the register button.
     * - Validates that both name fields are filled in and not placeholders
     * - Registers the new member in the LibrarySystem
     * - Displays a welcome message with their assigned generated Member ID.
     * - Launches the MemberDahsboard
     * - Closes registration window
     */
    private void handleRegister() {
        String firstName = firstNameEntry.getText().trim();
        String surname = surnameEntry.getText().trim();
        
        // Validate input: both fields must be filled and not placeholder text
        if (firstName.isEmpty() || surname.isEmpty() || firstName.equals("Enter Firstname") || surname.equals("Enter Surname")) {
            JOptionPane.showMessageDialog(this, "Please fill in both name fields.");
            return;
        }else{
            // Register new member in the system
            Member newMember = SYSTEM.registerMember(firstName, surname);

            // Show confirmation message with assigned Member ID 
            JOptionPane.showMessageDialog(this, "Welcome " + newMember.getFullName() + "! Your Member ID is: " + newMember.getMemberId() + 
                    "\nIf at any point you forget this please contact a staff member."
                            + "\nIt will always be visible at top right on your dashboard");

            // Launch member dashboard for the new member
            new MemberDashboard(SYSTEM, newMember).setVisible(true);
            // Close registration window
            dispose();
        }
    }

