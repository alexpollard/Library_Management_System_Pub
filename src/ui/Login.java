    /**
     * Toggle between Member and Staff Login modes.
     * Updates labels and visibility of password field.
     */    
    private void toggleRole() {
        isStaffLogin = !isStaffLogin;
        roleLabel.setText(isStaffLogin ? "Staff ID:" : "Member ID:");
        passwordEntryLabel.setVisible(isStaffLogin);
        staffPasswordEntry.setVisible(isStaffLogin);
    }
    
    /**
     * Handles login action when user presses the login button.
     * - If staff: launches StaffDashboard directly.
     * - If member: validates ID, checks reservations, and launches memberDashboard.
     */
    private void handleLogin() {        
        if (isStaffLogin) {
            // Staff login (no password check as no staff accounts in prototype)
            new StaffDashboard(SYSTEM).setVisible(true);
            dispose(); // close login window
        } else {
            try{
                // Parse member ID from text field
                int memberId = Integer.parseInt(userIdEntry.getText().trim());
                Member memberSignIn = SYSTEM.loginMember(memberId);
                
                if (memberSignIn != null) {
                    // Check if any reservations are ready for this member
                    List<Book> readyBooks = SYSTEM.checkReservationsForMember(memberId);
                    if (!readyBooks.isEmpty()) {
                        StringBuilder sb = new StringBuilder("The following reserved books are now available and have been checked out for you:\n");
                        for (Book b : readyBooks) {
                            sb.append(" - ").append(b.getTitle()).append("\n");
                        }
                        JOptionPane.showMessageDialog(this, sb.toString());
                    }
                    
                    // launch member dashboard
                    new MemberDashboard(SYSTEM, memberSignIn).setVisible(true);
                    dispose();
                } else {
                    JOptionPane.showMessageDialog(this, "Member not found.");
                }
            } catch (NumberFormatException ex) {
                JOptionPane.showMessageDialog(this, "Invalid Member ID.");
            }
        }
    }

